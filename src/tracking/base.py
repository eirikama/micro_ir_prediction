"""Tracker protocol — the interface every backend must satisfy."""
from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class Tracker(Protocol):
    """Backend-agnostic experiment tracker.

    Implementations: MLflowTracker, WandbTracker, NoOpTracker.
    Use ``build_tracker(cfg, run_name)`` to get the right one.
    """

    @property
    def run_id(self) -> str:
        """Unique identifier for this run (empty string for NoOp)."""
        ...

    # ── context manager ───────────────────────────────────────────────────────
    def __enter__(self) -> "Tracker": ...
    def __exit__(self, exc_type, exc_val, exc_tb) -> bool: ...

    # ── logging ───────────────────────────────────────────────────────────────
    def log_param(self, key: str, value) -> None: ...
    def log_params(self, params: dict) -> None: ...
    def log_metrics(self, metrics: dict, step: int | None = None) -> None: ...
    def log_metric(self, key: str, value: float, step: int | None = None) -> None: ...
    def set_tags(self, tags: dict) -> None: ...
    def set_tag(self, key: str, value: Any) -> None: ...
    def log_text(self, text: str, artifact_name: str) -> None: ...
    def log_dict(self, d: dict, artifact_name: str) -> None: ...

    # ── pytorch lightning integration ─────────────────────────────────────────
    def pl_logger(self) -> Any:
        """Return a PL-compatible Logger, or False to disable PL logging."""
        ...
